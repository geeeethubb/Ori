/** Small shared UI primitives: sheet (modal), toasts, spinner, empty/error states. */
import { createContext, useCallback, useContext, useEffect, useMemo, useRef, useState, type ReactNode } from 'react';

// ---------- Sheet ----------

interface SheetProps {
  open: boolean;
  onClose: () => void;
  title?: ReactNode;
  children: ReactNode;
  /** Sticky footer actions. */
  actions?: ReactNode;
  labelledBy?: string;
}

export function Sheet({ open, onClose, title, children, actions }: SheetProps) {
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    document.addEventListener('keydown', onKey);
    const prev = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
    return () => {
      document.removeEventListener('keydown', onKey);
      document.body.style.overflow = prev;
    };
  }, [open, onClose]);
  if (!open) return null;
  return (
    <div className="sheet-backdrop" onMouseDown={(e) => e.target === e.currentTarget && onClose()} role="presentation">
      <div className="sheet" role="dialog" aria-modal="true" ref={ref}>
        <div className="sheet-handle" aria-hidden="true" />
        {title !== undefined && (
          <div className="sheet-title">
            <h2 style={{ fontSize: '1.35rem' }}>{title}</h2>
            <button type="button" className="btn btn-ghost btn-icon" aria-label="Close" onClick={onClose}>
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round"><path d="M18 6 6 18M6 6l12 12" /></svg>
            </button>
          </div>
        )}
        {children}
        {actions && <div className="sheet-actions">{actions}</div>}
      </div>
    </div>
  );
}

// ---------- Toasts ----------

interface Toast {
  id: number;
  message: string;
  kind: 'info' | 'error';
  action?: { label: string; onClick: () => void };
}

interface ToastApi {
  toast: (message: string, opts?: { kind?: 'info' | 'error'; action?: Toast['action']; durationMs?: number }) => void;
}

const ToastContext = createContext<ToastApi>({ toast: () => undefined });

export function ToastProvider({ children }: { children: ReactNode }) {
  const [toasts, setToasts] = useState<Toast[]>([]);
  const counter = useRef(0);
  const toast = useCallback<ToastApi['toast']>((message, opts = {}) => {
    const id = ++counter.current;
    setToasts((t) => [...t.slice(-2), { id, message, kind: opts.kind ?? 'info', action: opts.action }]);
    window.setTimeout(() => setToasts((t) => t.filter((x) => x.id !== id)), opts.durationMs ?? (opts.kind === 'error' ? 7000 : 3500));
  }, []);
  const value = useMemo(() => ({ toast }), [toast]);
  return (
    <ToastContext.Provider value={value}>
      {children}
      <div className="toast-host" aria-live="polite">
        {toasts.map((t) => (
          <div key={t.id} className={`toast ${t.kind === 'error' ? 'toast-error' : ''}`} role="status">
            <span>{t.message}</span>
            {t.action && (
              <button type="button" className="btn btn-sm" onClick={() => { t.action?.onClick(); setToasts((x) => x.filter((y) => y.id !== t.id)); }}>
                {t.action.label}
              </button>
            )}
          </div>
        ))}
      </div>
    </ToastContext.Provider>
  );
}

export function useToast(): ToastApi {
  return useContext(ToastContext);
}

// ---------- misc ----------

export function Spinner({ label }: { label?: string }) {
  return (
    <span className="row" role="status" aria-live="polite" style={{ color: 'var(--ink-2)' }}>
      <span className="spinner" aria-hidden="true" />
      {label && <span className="small">{label}</span>}
    </span>
  );
}

export function EmptyState({ title, body, action }: { title: string; body?: ReactNode; action?: ReactNode }) {
  return (
    <div className="empty">
      <h3>{title}</h3>
      {body && <p>{body}</p>}
      {action}
    </div>
  );
}

export function ErrorBanner({ message, onRetry, retryLabel = 'Try again' }: { message: string; onRetry?: () => void; retryLabel?: string }) {
  return (
    <div className="banner banner-error" role="alert">
      <span>{message}</span>
      {onRetry && (
        <button type="button" className="btn btn-sm btn-secondary" onClick={onRetry}>
          {retryLabel}
        </button>
      )}
    </div>
  );
}

export function Skeleton({ h = 18, w = '100%', style }: { h?: number; w?: string | number; style?: React.CSSProperties }) {
  return <div className="skeleton" style={{ height: h, width: w, ...style }} aria-hidden="true" />;
}

