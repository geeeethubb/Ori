const GENERIC: Record<Pattern, Record<Purpose, string[]>> = {
  ...GENERIC_BASE,
  gallery: GENERIC_BASE.journal,
  practice: GENERIC_BASE.tracker,
  queue: GENERIC_BASE.board,
};

export function promptsFor(conceptId: string | undefined, pattern: Pattern, purpose: Purpose): string[] {
  const specific = conceptId ? CONCEPT_PROMPTS[conceptId] : undefined;
  return specific ?? GENERIC[pattern][purpose];
}

/** Title shown above the rotating prompt, e.g. "This week's challenge". */
export function promptTitle(cadence: 'daily' | 'weekly', pattern: Pattern): string {
  if (cadence === 'daily') return pattern === 'tracker' ? 'Today’s focus' : 'Today’s prompt';
  return pattern === 'board' ? 'This week’s focus' : 'This week’s challenge';
}
